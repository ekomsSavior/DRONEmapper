#!/usr/bin/env python3
"""Rebuild desktop and Android factual lookups from the reviewed web catalog."""
import hashlib
import json
from pathlib import Path
import re
import shutil

root=Path(__file__).resolve().parent.parent
target=root/'linux-node/dronemapper_node/data'
text=(root/'worker/rid-catalog.mjs').read_text()
match=re.search(r'export const rules\s*=\s*(\[.*\])\s*;',text,re.S)
if not match:
    raise SystemExit('FAA catalog layout changed; review it before refreshing')
rules=json.loads(match[1])
required={'start','end','manufacturer','model','device_type'}
allowed=required|{'evidence_url','reviewed_at','decimal_suffix'}
if not isinstance(rules,list) or not rules or any(not isinstance(row,dict) or not required<=row.keys() or row.keys()-allowed for row in rules):
    raise SystemExit('FAA catalog schema changed; review before refreshing')
for row in rules:
    if 'decimal_suffix' in row:
        width=row['decimal_suffix']
        if (type(width) is not int or not 1<=width<=len(row['start'])-5
                or len(row['start'])!=len(row['end'])
                or row['start'][:-width]!=row['end'][:-width]
                or not re.fullmatch('[0-9]+',row['start'][-width:])
                or not re.fullmatch('[0-9]+',row['end'][-width:])):
            raise SystemExit('Invalid decimal suffix constraint')
target.mkdir(parents=True,exist_ok=True)
(target/'rid-catalog.json').write_text(json.dumps(rules,ensure_ascii=False,indent=2)+'\n')
# Separate small methods keep the generated Java below the per-method bytecode
# limit. The scanner never fetches catalogs or needs Internet for identification.
java=root/'android-node/app/src/main/java/org/churchofmalware/dronemapper/node/ModelCatalog.java'
original=java.read_text()
body=original[original.index('  private ModelCatalog()'):].replace(
    '&& serial.compareTo(rule[1]) <= 0) {',
    '&& serial.compareTo(rule[1]) <= 0\n'
    '          && (rule[5].isEmpty() || serial.substring(serial.length() - Integer.parseInt(rule[5])).matches("[0-9]+"))) {')
parts=['/* Generated by linux-node/refresh-catalogs.py. Church of Malware / saviorSEC. GPL-2.0-only. */',
       'package org.churchofmalware.dronemapper.node;', '',
       'public final class ModelCatalog {',
       '  private static final String[][] RULES = buildRules();',
       '  private static String[][] buildRules() {',
       f'    String[][] result = new String[{len(rules)}][];']
chunks=[rules[i:i+100] for i in range(0,len(rules),100)]
for i,chunk in enumerate(chunks):
    parts.append(f'    System.arraycopy(part{i}(), 0, result, {i*100}, {len(chunk)});')
parts.extend(['    return result;', '  }'])
for i,chunk in enumerate(chunks):
    parts.append(f'  private static String[][] part{i}() {{ return new String[][] {{')
    for row in chunk:
        values=[row[k] for k in ('start','end','manufacturer','model','device_type')]
        values.append(str(row.get('decimal_suffix') or ''))
        parts.append('    {'+', '.join(json.dumps(v,ensure_ascii=True) for v in values)+'},')
    parts.append('  }; }')
java.write_text('\n'.join(parts)+'\n\n'+body)
assets=root/'android-node/app/src/main/assets'
provenance=json.loads((assets/'oui-vendors-provenance.json').read_text())
vendors=(assets/'oui-vendors.tsv').read_bytes()
if hashlib.sha256(vendors).hexdigest()!=provenance['sha256']:
    raise SystemExit('OUI catalog digest does not match its recorded provenance')
for name in ('oui-vendors.tsv','oui-vendors-provenance.json'):
    shutil.copyfile(assets/name,target/name)
print(f'Refreshed {len(rules)} FAA serial ranges and {provenance["prefix_count"]} OUI allocations.')
