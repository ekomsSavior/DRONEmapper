"""Build the browser's reviewed link directory: python3 scripts/build_device_links.py."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
catalog = json.loads((ROOT / "docs/device-links.json").read_text())
companies = {name: item["url"] for name, item in catalog["companies"].items()}
models = [[item["manufacturer"], item["model"], item.get("kind", ""), item["url"]] for item in catalog["models"]]
out = "// Generated by scripts/build_device_links.py; edit docs/device-links.json.\n"
out += "export const companyLinks = " + json.dumps(companies, ensure_ascii=False, indent=2) + ";\n"
out += "export const modelLinks = " + json.dumps(models, ensure_ascii=False, separators=(",", ":")) + ";\n"
(ROOT / "public/device-link-data.mjs").write_text(out)
print(f"Built {len(companies)} company and {len(models)} model links.")
