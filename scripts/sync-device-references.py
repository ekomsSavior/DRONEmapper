#!/usr/bin/env python3
"""Copy reviewed device facts to both offline scanners; never create sightings."""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
source = root / 'integration/security-device-references.json'
data = json.loads(source.read_text(encoding='utf-8'))
assert data['schema_version'] == 1
assert len(source.read_bytes()) <= 65536, 'Android reference asset limit'
vendors = {v['id']: v for v in data['vendors']}
assert len(vendors) == len(data['vendors']), 'Duplicate vendor ID'
matches = set()
for model in data['models']:
    assert model['vendor'] in vendors
    for key in ('url', 'source', 'manufacturer_url'):
        assert model[key].startswith('https://'), (model['name'], key)
    for maker in model.get('manufacturer_aliases', []):
        for alias in model.get('aliases', []):
            for kind in model.get('kinds', []):
                key = (maker.strip().lower(), alias.strip().lower(), kind)
                assert key not in matches, ('Ambiguous model match', key)
                matches.add(key)
for path in ('android-node/app/src/main/assets/security-device-references.json',
             'linux-node/dronemapper_node/data/security-device-references.json'):
    (root / path).write_bytes(source.read_bytes())
(root / 'public/security-device-data.mjs').write_text(
    '// Generated by scripts/sync-device-references.py; edit the integration JSON.\n'
    + 'export const deviceReferences = ' + json.dumps(data, ensure_ascii=False) + ';\n', encoding='utf-8')
print('Synced device references to website, Android and desktop.')
