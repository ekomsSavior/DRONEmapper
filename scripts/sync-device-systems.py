#!/usr/bin/env python3
"""Publish reviewed hardware profiles and existing model-bound RID references."""
import argparse
import json
from pathlib import Path
from export_developer_data import catalog_rules

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'public/device-system-data.mjs'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = json.loads((ROOT / 'integration/device-systems.json').read_text())
    keys = ('manufacturer', 'model', 'evidence_url')
    data['rid_models'] = [dict(zip(keys, row)) for row in sorted({tuple(r[k] for k in keys) for r in catalog_rules()})]
    content = '// Generated by scripts/sync-device-systems.py; edit integration/device-systems.json.\nexport const deviceSystems = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            raise SystemExit('Stale Device Library system data')
    else:
        TARGET.write_text(content)
    print(f"Device systems: {len(data['profiles'])} reviewed profiles")

if __name__ == '__main__':
    main()
