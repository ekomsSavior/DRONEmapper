#!/usr/bin/env python3
"""Publish the same reviewed model context to the map and both offline scanners."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'integration/drone-platforms.json'
data = json.loads(source.read_text())
assert data['schema_version'] == 1
seen = set()
for model in data['models']:
    for name in model['manufacturer_aliases']:
        for alias in model['aliases']:
            key = (name.strip().lower(), alias.strip().lower())
            assert key not in seen, key
            seen.add(key)
    for field in ('url', 'manufacturer_url', 'integration_url'):
        assert model[field].startswith('https://')
generated = '// Generated by scripts/sync-drone-platforms.py.\nexport const dronePlatforms = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
for directory in ('public', 'linux-node/dronemapper_node/static'):
    (root / directory / 'drone-platform-data.mjs').write_text(generated)
    (root / directory / 'drone-platforms.mjs').write_bytes((root / 'integration/drone-platforms.mjs').read_bytes())
(root / 'android-node/app/src/main/assets/drone-platforms.json').write_bytes(source.read_bytes())
print('Synced', len(data['models']), 'drone families to map, Android and desktop.')
