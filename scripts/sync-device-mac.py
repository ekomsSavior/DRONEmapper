#!/usr/bin/env python3
"""Publish the same explicitly reviewed MAC references used by the exports."""
import argparse
import json
from pathlib import Path
from export_developer_data import scoped_oui

ROOT=Path(__file__).resolve().parents[1]
TARGET=ROOT/'public/device-mac-data.mjs'
def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    data=scoped_oui()
    content='// Generated by scripts/sync-device-mac.py; edit integration/device-oui.json.\nexport const deviceMacData = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n'
    if args.check:
        if not TARGET.exists() or TARGET.read_text()!=content:raise SystemExit('Stale Device Library MAC data')
    else:TARGET.write_text(content)
    print(f"Device Library: {len(data['allocations'])} reviewed MAC allocations")
if __name__=='__main__':main()
