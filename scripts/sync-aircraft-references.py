#!/usr/bin/env python3
"""Sync reviewed aircraft facts to the map and offline scanners."""
import json
from pathlib import Path
r=Path(__file__).resolve().parents[1];source=r/'integration/aircraft-references.json';data=json.loads(source.read_text())
assert data['schema_version']==1 and len(source.read_bytes())<65536
seen=set()
for m in data['models']:
    assert m['id'] not in seen;seen.add(m['id'])
    for maker in m['manufacturer_aliases']:
        for alias in m['aliases']:
            key=(maker.strip().lower(),alias.strip().lower());assert key not in seen,key;seen.add(key)
    for url in [m['url'],m['manufacturer_url'],*m['sources']]:assert url.startswith('https://')
for directory in ('public','linux-node/dronemapper_node/static'):
    (r/directory/'aircraft-reference-data.mjs').write_text('// Generated by scripts/sync-aircraft-references.py.\nexport const aircraftReferences = '+json.dumps(data,indent=2)+';\n')
    (r/directory/'aircraft-references.mjs').write_bytes((r/'integration/aircraft-references.mjs').read_bytes())
for path in ('android-node/app/src/main/assets/aircraft-references.json','linux-node/dronemapper_node/data/aircraft-references.json'):(r/path).write_bytes(source.read_bytes())
print('Synced',len(data['models']),'aircraft references.')
