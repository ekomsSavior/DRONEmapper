"""Generate shared receive-only pattern catalog. Never promotes matches to identities."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'integration/robot-signatures.json').read_text())
rules = data['rules']
assert len({r['id'] for r in rules}) == len(rules)
encoded = json.dumps(data, indent=2, ensure_ascii=False) + '\n'
for relative in ('linux-node/dronemapper_node/data/robot-signatures.json',
                 'android-node/app/src/main/assets/robot-signatures.json'):
    (ROOT / relative).write_text(encoded)
(ROOT / 'public/robot-signatures.mjs').write_text(
    '/* Generated from integration/robot-signatures.json. */\n'
    + 'export const robotSignatures = ' + encoded.rstrip() + ';\n'
    + "export const robotRule = id => robotSignatures.rules.find(r=>r.id===id);\n"
    + "export const robotWifiSignature = name => typeof name === 'string' ? robotSignatures.rules.find(r=>r.transport==='wifi'&&new RegExp('^(?:'+r.name_pattern+')$','u').test(name)&&!/[\\r\\n]/.test(name))?.id || null : null;\n")
q = lambda s: json.dumps(s, ensure_ascii=False)
rows = ',\n'.join('    {' + ', '.join(q(r[k]) for k in ('id','transport','family','label','name_pattern','scope')) + '}' for r in rules)
java = '''/* Generated by scripts/build_robot_signatures.py. */
package org.churchofmalware.dronemapper.node;
import java.util.Arrays;
public final class RobotSignals {
  public static final String CYBERDOG_UUID = "0000c420-0000-1000-8000-00805f9b34fb";
  public static final String CYBERDOG_SIGNATURE = "cyberdog-ble-v1";
  private RobotSignals() {}
  private static final String[][] RULES = {
ROWS
  };
  private static String[] rule(String id) {
    for (String[] r : RULES) if (r[0].equals(id)) return r;
    return null;
  }
  public static boolean isRobot(String id) { return rule(id) != null; }
  public static boolean isBle(String id) { String[] r=rule(id); return r!=null && r[1].equals("ble"); }
  public static String describe(String id) { String[] r=rule(id); return r==null ? "Possible ground robot" : r[3]; }
  public static String scope(String id) { String[] r=rule(id); return r==null ? "" : r[5]; }
  public static String wifi(String name) {
    if (name==null) return null;
    for (String[] r : RULES) if (r[1].equals("wifi") && name.matches(r[4])) return r[0];
    return null;
  }
  public static boolean cyberdog(String name, boolean hasService, byte[] data) {
    return name!=null && name.matches(RULES[0][4]) && hasService
        && Arrays.equals(data,new byte[]{0,1,2,3,4});
  }
  public static String bluetooth(String name, boolean hasCyberdogService, byte[] data) {
    if (cyberdog(name,hasCyberdogService,data)) return CYBERDOG_SIGNATURE;
    if (name==null) return null;
    for (String[] r : RULES) if (r[1].equals("ble") && !r[0].equals(CYBERDOG_SIGNATURE) && name.matches(r[4])) return r[0];
    return null;
  }
}
'''.replace('ROWS', rows)
(ROOT / 'android-node/app/src/main/java/org/churchofmalware/dronemapper/node/RobotSignals.java').write_text(java)
print(f'Generated {len(rules)} robot patterns for Android, desktop and website.')

platforms = (ROOT / 'integration/robot-platforms.json').read_text()
for path in ('android-node/app/src/main/assets/robot-platforms.json', 'linux-node/dronemapper_node/data/robot-platforms.json'):
    (ROOT / path).write_text(platforms)
(ROOT / 'public/robot-platforms.mjs').write_text('export const robotPlatforms = ' + platforms.rstrip() + ';\n')
